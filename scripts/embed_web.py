# PlatformIO pre-build step: gzips every page in web/ into src/web/WebAssets.h,
# so the firmware serves them without a file system. Each web/<name>.<ext>
# becomes web_assets::k<Name><Ext>, e.g. index.html -> kIndexHtml.
import gzip
import re
from pathlib import Path

Import("env")  # noqa: F821 (provided by PlatformIO)

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css",
    ".js": "text/javascript",
    ".svg": "image/svg+xml",
}


def symbol(path):
    words = re.split(r"[^A-Za-z0-9]+", path.name)
    return "k" + "".join(word[:1].upper() + word[1:] for word in words if word)


def generate(sources):
    lines = [
        "// Generated by scripts/embed_web.py from web/; do not edit.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "struct WebAsset {",
        "  const char* type;",
        "  const uint8_t* data;  // gzip-compressed",
        "  size_t size;",
        "};",
        "",
        "namespace web_assets {",
    ]
    for path in sources:
        name = symbol(path)
        # mtime=0 keeps the output identical between builds.
        data = gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)
        lines.append(f"constexpr uint8_t {name}Data[] = {{")
        for i in range(0, len(data), 20):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 20]) + ",")
        lines.append("};")
        lines.append(
            f'constexpr WebAsset {name}{{"{TYPES[path.suffix]}", {name}Data, sizeof {name}Data}};'
        )
    lines += ["}  // namespace web_assets", ""]
    return "\n".join(lines)


def main():
    project = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
    sources = sorted(p for p in (project / "web").iterdir() if p.suffix in TYPES)
    output = project / "src" / "web" / "WebAssets.h"
    text = generate(sources)
    # Only rewrite on changes, so unchanged pages don't trigger a rebuild.
    if not output.exists() or output.read_text(encoding="utf-8") != text:
        output.parent.mkdir(exist_ok=True)
        with open(output, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"embed_web: wrote {output.relative_to(project)}")


main()
